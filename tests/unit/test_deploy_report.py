"""The deploy's two issues: which one a run opens, and what closes them (docs/11 §7.7).

Run `38774620886` went red on a transient edge error and opened nothing, because the only
workflow that writes to production was the only one without an issue step. These tests hold
the classification, the workflow wiring it depends on, and the `gh` calls it makes.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
import yaml

from loremfile import deploy_report, gh_issue
from loremfile.deploy_report import PUBLISH_TITLE, VERIFY_TITLE, plan

ROOT = Path(__file__).resolve().parents[2]
WORKFLOW = yaml.safe_load((ROOT / ".github/workflows/deploy.yml").read_text(encoding="utf-8"))
RUN = "https://github.com/owner/loremfile/actions/runs/1"


def ran(*ok: str, failed: str = "", soft_failed: str = "") -> dict[str, Any]:
    """A `toJSON(steps)` for a run in which `ok` succeeded and `failed` failed."""
    steps = {sid: {"outcome": "success", "conclusion": "success"} for sid in ok}
    if failed:
        steps[failed] = {"outcome": "failure", "conclusion": "failure"}
    if soft_failed:  # continue-on-error: the step failed, the job did not
        steps[soft_failed] = {"outcome": "failure", "conclusion": "success"}
    return steps


BEFORE_PUBLISHING = ("checkout", "install", "git_safe", "carry", "only", "generate", "validate")
EVERYTHING_BUT_VERIFY = tuple(
    sid for sid, _, _ in deploy_report.STEPS if sid not in ("verify", "indexnow")
)


def run_plan(result: str, steps: dict[str, Any], **kwargs: Any) -> list[deploy_report.Action]:
    defaults: dict[str, Any] = {
        "staged": False,
        "run_url": RUN,
        "commit": "6c637bcbe9fbd444",
        "verify_errors": [],
    }
    return plan(result, steps, **{**defaults, **kwargs})


# --- which issue a run opens or closes ----------------------------------------------------


def test_a_full_green_deploy_closes_both() -> None:
    actions = run_plan("success", ran(*EVERYTHING_BUT_VERIFY, "verify", "indexnow"))
    assert [(a.title, a.state) for a in actions] == [(PUBLISH_TITLE, "ok"), (VERIFY_TITLE, "ok")]


def test_a_failed_indexnow_is_still_a_green_deploy() -> None:
    """continue-on-error: the step's outcome is failure, its conclusion success."""
    actions = run_plan("success", ran(*EVERYTHING_BUT_VERIFY, "verify", soft_failed="indexnow"))
    assert {a.state for a in actions} == {"ok"}


def test_a_staged_green_run_closes_nothing() -> None:
    assert run_plan("success", ran(*EVERYTHING_BUT_VERIFY, "verify"), staged=True) == []


def test_a_failure_before_publishing_leaves_production_untouched() -> None:
    [action] = run_plan("failure", ran(*BEFORE_PUBLISHING, failed="manifest_check"))
    assert (action.title, action.state) == (PUBLISH_TITLE, "failing")
    summary = action.report["summary"]
    assert summary["failing step"] == "Check the regenerated bytes against the manifest"
    assert summary["production"].startswith("untouched")
    assert summary["run"] == RUN
    assert summary["commit"] == "6c637bcbe9fb"
    assert action.report["errors"][0] == "publishing steps that completed: none"


def test_a_failure_after_a_publishing_step_says_half_updated_and_names_what_completed() -> None:
    steps = ran(
        *BEFORE_PUBLISHING,
        "manifest_check",
        "publish_fixtures",
        "apply_removals",
        "build_site",
        failed="publish_site",
    )
    [action] = run_plan("failure", steps)
    assert action.title == PUBLISH_TITLE
    assert action.report["summary"]["production"] == "may be half-updated"
    errors = action.report["errors"]
    assert errors[0] == "publishing steps that completed: Publish fixtures, Apply removals"
    assert "Publish the site may have written part of its work" in errors[1]
    assert errors[-1] == deploy_report.LOG_NOTE


def test_a_failed_check_opens_the_verify_issue_and_closes_the_publish_one() -> None:
    lines = ["error: srt/3-cues.srt: status 500", "error: /mp3: timeout no response"]
    actions = run_plan("failure", ran(*EVERYTHING_BUT_VERIFY, failed="verify"), verify_errors=lines)
    assert [(a.title, a.state) for a in actions] == [
        (PUBLISH_TITLE, "ok"),
        (VERIFY_TITLE, "failing"),
    ]
    report = actions[1].report
    assert report["summary"]["production"].startswith("published")
    assert report["errors"] == [*lines, deploy_report.LOG_NOTE]


def test_a_staged_failed_check_only_opens() -> None:
    actions = run_plan("failure", ran(*EVERYTHING_BUT_VERIFY, failed="verify"), staged=True)
    assert [(a.title, a.state) for a in actions] == [(VERIFY_TITLE, "failing")]


@pytest.mark.parametrize("result", ["cancelled", "failure"])
def test_a_job_that_reported_no_steps_is_a_publish_failure_of_unknown_extent(result: str) -> None:
    """A timeout or a cancellation leaves no step outputs; that is never read as green."""
    [action] = run_plan(result, {})
    assert (action.title, action.state) == (PUBLISH_TITLE, "failing")
    assert action.report["summary"]["production"].startswith("unknown")
    assert result in action.report["summary"]["failing step"]


def test_a_publish_drill_says_production_is_untouched_because_it_is() -> None:
    """The injection exits before the upload call, so the code knows nothing was written;
    saying "may be half-updated" there would teach the reader to discount the field."""
    steps = ran(*BEFORE_PUBLISHING, "manifest_check", failed="publish_fixtures")
    [action] = run_plan("failure", steps, drill="publish")
    assert action.report["summary"]["production"] == (
        "untouched: the drill stopped Publish fixtures before its upload call"
    )
    assert not any("may have written" in line for line in action.report["errors"])
    # Control: the same failure without the drill is a real one, and stays cautious.
    [real] = run_plan("failure", steps)
    assert real.report["summary"]["production"] == "may be half-updated"
    # The verify drill's wording is unchanged: its stage really did publish.
    [_, verify] = run_plan("failure", ran(*EVERYTHING_BUT_VERIFY, failed="verify"), drill="verify")
    assert verify.report["summary"]["production"].startswith("published")


def test_the_publish_injection_runs_before_the_upload_call() -> None:
    """What makes "untouched" true: the drill's exit precedes the upload in the step itself."""
    run = next(s for s in deploy_steps() if s["id"] == "publish_fixtures")["run"]
    assert run.index('"publish" ]; then') < run.index("exit 1") < run.index("loremfile upload")


def test_a_drill_says_so_in_the_body() -> None:
    [action] = run_plan(
        "failure",
        ran(*BEFORE_PUBLISHING, "manifest_check", failed="publish_fixtures"),
        drill="publish",
    )
    assert action.report["summary"]["drill"] == "inject_failure=publish"


# --- the check's error lines ---------------------------------------------------------------


def test_only_error_lines_reach_the_body_and_at_most_twenty(tmp_path: Path) -> None:
    log = tmp_path / "verify-live.txt"
    log.write_text(
        "  415 checked, 5 failing\n" + "".join(f"error: /p{i}: status 500\n" for i in range(25))
    )
    found = deploy_report.error_lines(log)
    assert len(found) == 20
    assert found[0] == "error: /p0: status 500"


def test_a_missing_log_gives_no_lines_rather_than_a_crash(tmp_path: Path) -> None:
    assert deploy_report.error_lines(tmp_path / "absent.txt") == []


def test_the_errors_subcommand_writes_one_step_output_line(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    log = tmp_path / "verify-live.txt"
    log.write_text("error: /avif: timeout no response\n")
    assert deploy_report.main(["errors", str(log)]) == 0
    assert capsys.readouterr().out == 'errors=["error: /avif: timeout no response"]\n'


# --- the workflow the classification depends on --------------------------------------------


def deploy_steps() -> list[dict[str, Any]]:
    return list(WORKFLOW["jobs"]["deploy"]["steps"])


def test_every_deploy_step_has_the_id_and_name_the_module_expects() -> None:
    """A step without an id is invisible to `toJSON(steps)`, so its failure would read as
    'the job ended before it said where'. Named, so an empty list cannot pass."""
    found = [(step.get("id"), step.get("name")) for step in deploy_steps()]
    assert found == [(sid, name) for sid, name, _ in deploy_report.STEPS]
    assert ("verify", "Verify what was published") in found


def test_the_publishing_steps_are_the_ones_that_write() -> None:
    writes = {"publish_fixtures", "apply_removals", "publish_site", "purge", "infra_apply"}
    assert writes == deploy_report.WRITES


def test_the_deploy_job_hands_its_steps_and_the_check_errors_to_the_report_job() -> None:
    outputs = WORKFLOW["jobs"]["deploy"]["outputs"]
    assert outputs["steps"] == "${{ toJSON(steps) }}"
    assert outputs["verify_errors"] == "${{ steps.verify.outputs.errors }}"
    verify = next(step for step in deploy_steps() if step["id"] == "verify")
    assert verify["shell"] == "bash"
    assert "pipefail" in verify["run"]
    assert 'deploy_report errors build/verify-live.txt >> "$GITHUB_OUTPUT"' in verify["run"]


def test_the_report_job_runs_after_any_outcome_and_alone_can_write_issues() -> None:
    jobs = WORKFLOW["jobs"]
    report = jobs["report"]
    assert report["needs"] == ["setup", "deploy"]
    assert "always()" in report["if"]
    assert "== 'deploy'" in report["if"], "a dry run publishes nothing and reports nothing"
    assert report["permissions"] == {"contents": "read", "issues": "write"}
    assert "issues" not in WORKFLOW["permissions"]
    assert "permissions" not in jobs["deploy"]
    step = report["steps"][-1]
    assert step["run"] == "python -m loremfile.deploy_report report"
    assert step["env"]["RESULT"] == "${{ needs.deploy.result }}"


def test_a_drill_outside_a_real_deploy_is_refused_first() -> None:
    """Run 38891535447: a drill left at the dry-run default failed a stage that publishes
    nothing, the report job skipped it, and the run looked like a broken deploy."""
    guard = deploy_steps()[0]
    assert guard["id"] == "drill_guard"
    condition = guard["if"]
    assert "inputs.inject_failure != 'none'" in condition
    assert "inputs.inject_failure != ''" in condition, "a push carries no inputs and must pass"
    assert "env.MODE != 'deploy'" in condition
    assert "the drill needs mode: deploy" in guard["run"]
    assert guard["run"].rstrip().endswith("exit 1")


@pytest.mark.parametrize(
    ("stage", "step_id"), [("publish", "publish_fixtures"), ("verify", "verify")]
)
def test_the_drill_fails_its_stage_on_purpose(stage: str, step_id: str) -> None:
    options = WORKFLOW[True]["workflow_dispatch"]["inputs"]["inject_failure"]["options"]
    assert options == ["none", "publish", "verify"]
    step = next(step for step in deploy_steps() if step["id"] == step_id)
    assert step["env"]["INJECT"] == "${{ inputs.inject_failure }}"
    assert f'"${{INJECT:-none}}" = "{stage}"' in step["run"]


# --- the gh calls, at the subprocess boundary ----------------------------------------------


class GhRecorder:
    """Replaces `subprocess.run` under `gh_issue`, so the real `_gh` builds the real argv."""

    def __init__(self, monkeypatch: pytest.MonkeyPatch, open_issues: list[dict[str, Any]]) -> None:
        self.calls: list[list[str]] = []
        self.open_issues = open_issues
        monkeypatch.setattr(gh_issue.shutil, "which", lambda _name: "/usr/bin/gh")
        monkeypatch.setattr(gh_issue.subprocess, "run", self._run)

    def _run(self, argv: list[str], **_kwargs: object) -> object:
        self.calls.append(list(argv))
        stdout = json.dumps(self.open_issues) if argv[1:3] == ["issue", "list"] else "https://x/1"
        return gh_issue.subprocess.CompletedProcess(argv, 0, stdout=stdout, stderr="")

    def ops(self) -> list[tuple[str, str]]:
        """(operation, title or issue number) for every write."""
        found = []
        for argv in self.calls:
            if argv[2] == "create":
                found.append(("create", argv[argv.index("--title") + 1]))
            elif argv[2] in ("comment", "close"):
                found.append((argv[2], argv[3]))
        return found


def set_run(
    monkeypatch: pytest.MonkeyPatch, result: str, steps: dict[str, Any], errors: list[str]
) -> None:
    monkeypatch.setenv("GITHUB_REPOSITORY", "owner/loremfile")
    monkeypatch.setenv("RESULT", result)
    monkeypatch.setenv("STEPS", json.dumps(steps))
    monkeypatch.setenv("VERIFY_ERRORS", json.dumps(errors))
    monkeypatch.setenv("RUN_URL", RUN)
    monkeypatch.setenv("COMMIT", "6c637bcbe9fbd444")
    monkeypatch.delenv("ONLY", raising=False)
    monkeypatch.delenv("INJECT", raising=False)


def test_a_failed_check_opens_one_issue_under_the_deploy_label(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    set_run(
        monkeypatch,
        "failure",
        ran(*EVERYTHING_BUT_VERIFY, failed="verify"),
        ["error: /hls: timeout no response"],
    )
    gh = GhRecorder(monkeypatch, open_issues=[])
    assert deploy_report.report(tmp_path) == 0
    assert gh.ops() == [("create", VERIFY_TITLE)]
    create = next(argv for argv in gh.calls if argv[2] == "create")
    assert create[create.index("--label") + 1] == "deploy"
    body = create[create.index("--body") + 1]
    assert RUN in body
    assert "Verify what was published" in body
    assert "error: /hls: timeout no response" in body
    assert all("--repo" in argv for argv in gh.calls)


def test_a_recurring_transient_error_comments_on_the_open_issue_instead_of_opening_another(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    set_run(
        monkeypatch,
        "failure",
        ran(*EVERYTHING_BUT_VERIFY, failed="verify"),
        ["error: /avif: timeout no response"],
    )
    gh = GhRecorder(monkeypatch, open_issues=[{"number": 101, "title": VERIFY_TITLE}])
    deploy_report.report(tmp_path)
    assert gh.ops() == [("comment", "101")]


def test_the_next_full_deploy_closes_what_is_open(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    set_run(monkeypatch, "success", ran(*EVERYTHING_BUT_VERIFY, "verify"), [])
    gh = GhRecorder(monkeypatch, open_issues=[{"number": 101, "title": VERIFY_TITLE}])
    deploy_report.report(tmp_path)
    assert gh.ops() == [("close", "101")]
