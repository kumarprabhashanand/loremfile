"""A deploy's outcome as the two `deploy` issues (docs/09 §3.2, docs/11 §7.7).

The deploy is the only workflow that writes to production, and until 2026-10-16 it was the
only one that failed without opening an issue: run `38774620886` went red on a transient
edge error and nobody was told. A failed deploy needs one of two responses, so it opens one
of two issues:

- **Deploy did not publish cleanly**: a step before the post-deploy check failed, or the job
  stopped without reporting its steps. Production may be half-updated, so the body names
  every publishing step that completed and the one that failed.
- **Deploy published but did not verify**: every publishing step completed and the check
  that reads production back failed. Production is probably fine but unverified, so the
  body carries the check's own error lines.

Both go through `gh_issue`, so a transient error that recurs adds a comment to the open
issue rather than opening another, and each closes on the next full deploy that gets past
its stage. A staged run (`only`) proves nothing about the paths it skipped, so it opens but
never closes.
"""

from __future__ import annotations

import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from loremfile import gh_issue

LABEL = "deploy"
PUBLISH_TITLE = "Deploy did not publish cleanly"
VERIFY_TITLE = "Deploy published but did not verify"
#: The step whose failure means "published but unverified" rather than "not published".
VERIFY = "verify"
#: The deploy job's steps in order: `id`, name, and whether the step writes to production.
#: `tests/unit/test_deploy_report.py` holds this equal to `deploy.yml`.
STEPS: tuple[tuple[str, str, bool], ...] = (
    ("drill_guard", "Refuse a drill outside a real deploy", False),
    ("checkout", "Check out the repository", False),
    ("install", "Install the package", False),
    ("git_safe", "Let git read the checkout", False),
    ("carry", "Fetch the fixtures that cannot be rebuilt", False),
    ("only", "Expand the paths to publish", False),
    ("generate", "Generate what the bucket is missing", False),
    ("validate", "Validate the generated bytes", False),
    ("manifest_check", "Check the regenerated bytes against the manifest", False),
    ("publish_fixtures", "Publish fixtures", True),
    ("apply_removals", "Apply removals", True),
    ("build_site", "Build the site", False),
    ("publish_site", "Publish the site", True),
    ("purge", "Purge the site from the cache", True),
    ("infra_changed", "Decide whether infra/ changed since the last successful deploy", False),
    ("infra_dry_run", "Show what an infra apply would do", False),
    ("infra_apply", "Apply infra when infra/ changed or requested", True),
    (VERIFY, "Verify what was published", False),
    ("indexnow", "Tell IndexNow which pages changed", False),
)
NAMES = {step_id: name for step_id, name, _ in STEPS}
WRITES = {step_id for step_id, _, writes in STEPS if writes}
#: An unexplained 500 is worth being able to look up after the run's log has gone.
LOG_NOTE = (
    "Actions keeps this run's log for 90 days. If the cause is not understood, copy the "
    "failing step's output into this issue before then (docs/11 §7.7)."
)
ERROR_PREFIX = "error: "
MAX_ERRORS = 20


@dataclass(frozen=True)
class Action:
    title: str
    state: str  # failing | ok
    report: dict[str, Any]


def _conclusion(steps: dict[str, Any], step_id: str) -> str:
    step = steps.get(step_id)
    return str(step.get("conclusion", "")) if isinstance(step, dict) else ""


def plan(
    result: str,
    steps: dict[str, Any],
    *,
    staged: bool,
    run_url: str,
    commit: str,
    verify_errors: list[str],
    drill: str = "",
) -> list[Action]:
    """What to do with each issue, given the deploy job's result and its steps' outcomes.

    `conclusion`, not `outcome`: a `continue-on-error` step that failed concludes `success`,
    and IndexNow is one, by design.
    """
    summary: dict[str, str] = {"run": run_url, "commit": commit[:12]}
    if drill:
        summary["drill"] = f"inject_failure={drill}"
    green = {"command": "deploy", "ok": True, "summary": summary, "errors": []}
    if result == "success":
        return (
            []
            if staged
            else [Action(PUBLISH_TITLE, "ok", green), Action(VERIFY_TITLE, "ok", green)]
        )

    failing = next((sid for sid, _, _ in STEPS if _conclusion(steps, sid) == "failure"), None)
    if failing == VERIFY:
        report = {
            "command": "deploy",
            "ok": False,
            "summary": {
                **summary,
                "failing step": NAMES[VERIFY],
                "production": "published; the post-deploy check failed, so it is unverified",
            },
            "errors": [*(verify_errors or ["the check printed no error lines"]), LOG_NOTE],
        }
        closing = [] if staged else [Action(PUBLISH_TITLE, "ok", green)]
        return [*closing, Action(VERIFY_TITLE, "failing", report)]

    completed = [
        NAMES[sid] for sid, _, _ in STEPS if sid in WRITES and _conclusion(steps, sid) == "success"
    ]
    if failing is None:
        step = f"none reported: the job ended `{result}` before it said where"
        production = "unknown: read the run log for the last step that ran"
    elif completed or failing in WRITES:
        step, production = NAMES[failing], "may be half-updated"
    else:
        step, production = NAMES[failing], "untouched: the failure came before any publishing step"
    errors = [f"publishing steps that completed: {', '.join(completed) or 'none'}"]
    if failing in WRITES:
        errors.append(f"{NAMES[failing]} may have written part of its work before it failed")
    report = {
        "command": "deploy",
        "ok": False,
        "summary": {**summary, "failing step": step, "production": production},
        "errors": [*errors, LOG_NOTE],
    }
    return [Action(PUBLISH_TITLE, "failing", report)]


def error_lines(log: Path) -> list[str]:
    """The `error:` lines a command printed, at most twenty, for the issue body."""
    try:
        text = log.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    found = [line.rstrip() for line in text.splitlines() if line.startswith(ERROR_PREFIX)]
    return found[:MAX_ERRORS]


def _json_env(name: str, default: Any) -> Any:  # noqa: ANN401 - JSON from a job output
    """A job output parsed, or `default` when the job never set it (a timeout, a cancel)."""
    try:
        return json.loads(os.environ.get(name, "") or "null") or default
    except ValueError:
        return default


def report(out_dir: Path) -> int:
    """Reconcile the two issues with this run. Reads everything from the environment."""
    actions = plan(
        os.environ.get("RESULT", ""),
        _json_env("STEPS", {}),
        staged=bool(os.environ.get("ONLY", "").strip()),
        run_url=os.environ.get("RUN_URL", ""),
        commit=os.environ.get("COMMIT", ""),
        verify_errors=_json_env("VERIFY_ERRORS", []),
        drill="" if os.environ.get("INJECT", "none") in ("", "none") else os.environ["INJECT"],
    )
    if not actions:
        print("a staged run succeeded; it proves nothing about other paths, so nothing closes")  # noqa: T201
        return 0
    out_dir.mkdir(parents=True, exist_ok=True)
    status = 0
    for number, action in enumerate(actions):
        path = out_dir / f"deploy-{number}.json"
        path.write_text(json.dumps(action.report), encoding="utf-8")
        try:
            outcome = gh_issue.apply(
                label=LABEL, title=action.title, report=path, state=action.state
            )
        except gh_issue.IssueError as exc:
            print(f"{action.title}: error: {exc}")  # noqa: T201
            status = 1
            continue
        print(f"{action.title}: {outcome.action} {outcome.number or ''} {outcome.detail}".strip())  # noqa: T201
    return status


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) == 2 and args[0] == "errors":  # noqa: PLR2004 - subcommand and its file
        print("errors=" + json.dumps(error_lines(Path(args[1]))))  # noqa: T201
        return 0
    if args == ["report"]:
        return report(Path("build"))
    print("usage: python -m loremfile.deploy_report (errors FILE | report)")  # noqa: T201
    return 2


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
