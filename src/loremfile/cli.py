@infra.command("apply")
@click.option(
    "--dry-run",
    is_flag=True,
    help="Resolve and print the plan, including the target zone, without writing.",
)
@click.option("--json", "as_json", is_flag=True, help="Print one JSON object.")
def infra_apply(dry_run: bool, as_json: bool) -> None:
    """Apply infra/ to Cloudflare (docs/08 §6). Runs from infra.yml, never locally.

    The zone is verified against its hostname before anything writes, and the plan names
    the zone it resolved: ruleset entry points are written with a full PUT, and this
    account holds unrelated production zones.
    """
    errors: list[str] = []
    items: list[Item] = []
    summary: dict[str, Any] = {}
    try:
        client = Client.from_env(dry_run=dry_run)
        report = apply_infra.run(client)
        click.echo(report.render(), err=True)
        items = [
            {"path": o.resource, "status": o.state, "detail": o.detail} for o in report.outcomes
        ]
        summary = {
            "zone": report.hostname,
            "zone_id": report.zone_id,
            "dry_run": dry_run,
            **{
                state: sum(1 for o in report.outcomes if o.state == state)
                for state in ("unchanged", "updated", "skipped", "manual", "failed")
            },
        }
        errors = [f"{o.resource}: {o.detail}" for o in report.outcomes if o.state == "failed"]
    except ZoneScopeError as exc:
        # Never folded into the generic handler: this is the guard that protects the
        # other zones on the account, and it must read as its own kind of failure.
        errors.append(f"ZONE SCOPE REFUSED — nothing was written: {exc}")
    except CloudflareError as exc:
        errors.append(str(exc))
    sys.exit(
        _emit(
            "infra apply",
            ok=not errors,
            summary=summary,
            items=items,
            errors=errors,
            as_json=as_json,
        )
    )


@main.command("upload")
@click.option("--fixtures", "fixtures", is_flag=True, help="Publish missing manifest entries.")
@click.option(
    "--apply-removals",
    "removals",
    is_flag=True,
    help="Delete objects whose manifest entry is status: removed (takedown flow).",
)
@click.option("--site", "site", is_flag=True, help="Publish build/site/ (M4.1).")
@click.option(
    "--carry-forward",
    "carry_forward",
    type=click.Path(path_type=Path, file_okay=False),
    help="Directory holding the bytes of expected_drift fixtures (the CI artifact).",
)
@click.option(
    "--only",
    "only",
    multiple=True,
    metavar="PATH",
    help="Publish only these manifest paths (staged first publish).",
)
@click.option("--dry-run", "dry_run", is_flag=True, help="Print the plan; write nothing.")
@click.option("--json", "as_json", is_flag=True, help="Print one JSON object.")
def upload_command(
    fixtures: bool,
    removals: bool,
    site: bool,
    carry_forward: Path | None,
    only: tuple[str, ...],
    dry_run: bool,
    as_json: bool,
) -> None:
    """Publish to R2 (docs/09 §5). Needs T2; never overwrites a fixture."""
    errors: list[str] = []
    summary: dict[str, Any] = {}
    items: list[Item] = []
    chosen = [
        name
        for name, on in (("--fixtures", fixtures), ("--apply-removals", removals), ("--site", site))
        if on
    ]
    if len(chosen) != 1:
        sys.exit(
            _emit(
                "upload",
                ok=False,
                summary={},
                items=[],
                errors=["choose exactly one of --fixtures, --apply-removals, --site"],
                as_json=as_json,
            )
        )
    try:
        if site:
            raise UploadUnavailable(
                "--site needs `loremfile site build`, which arrives with M4.1. Publishing "
                "an empty build/site/ would report success for a site that does not "
                "exist. `--force-site` arrives with it, for the same reason: an option "
                "that changes nothing is worse than an absent one."
            )
        manifest = Manifest.load()
        bucket = r2_module.bucket_name()
        s3 = r2_module.client()
        if fixtures:
            # `--only` narrows the *plan*, so the gates still run over exactly the keys
            # that are about to be written and no others: a staged publish gets the same
            # lock and carry-forward checks as a full one, not a weaker pass.
            entries = _restrict(list(manifest.active), only)
            live = r2_module.live_hashes(s3, bucket, [e["path"] for e in entries])
            catalog_obj = Catalog.load()
            available = upload_module.sources(
                [e["path"] for e in entries],
                catalog=catalog_obj,
                build_dir=build_module.fixtures_dir(),
                carry_forward=carry_forward,
            )
            plan = upload_module.plan_fixtures(
                entries,
                live,
                available,
                catalog=catalog_obj,
                lock_rules=locks.committed_rules(),
            )
            # Hash what is about to be published. The carry-forward bytes come from a
            # different workflow run, so they are untrusted input; this is what makes
            # downloading that artifact loosely safe.
            plan.blockers += upload_module.verify_sources(plan, entries)
        else:
            # Only the tombstones. HEADing every published fixture to find out which of
            # them is being removed would be ~160 Class B reads to answer a question the
            # manifest already answers.
            tombstoned = [
                e["path"] for e in _restrict(manifest.entries, only) if e.get("status") == "removed"
            ]
            live = r2_module.live_hashes(s3, bucket, tombstoned)
            plan = upload_module.plan_removals(manifest.entries, live)

        click.echo(plan.render(), err=True)
        by_path = manifest.by_path
        done = 0
        if plan.ok and not dry_run:
            for step in plan.steps:
                if step.action is upload_module.Action.UPLOAD:
                    entry = by_path[step.key]
                    r2_module.put_fixture(
                        s3,
                        bucket,
                        step.key,
                        Path(step.source),
                        mime=str(entry["mime"]),
                        sha256=str(entry["sha256"]),
                    )
                    done += 1
                elif step.action is upload_module.Action.REMOVE:
                    r2_module.delete(s3, bucket, step.key)
                    # docs/09 §5: delete *and* purge. A removed object still cached at
                    # the edge is still being served, which is the only thing a takedown
                    # is measured on.
                    purged = purge_module.purge_removed_url(
                        _zone_client(), f"https://{config.SITE_HOST}/{step.key}"
                    )
                    errors += purged.errors
                    done += 1
        summary = {
            "mode": chosen[0].lstrip("-"),
            "uploaded": len(plan.by_action(upload_module.Action.UPLOAD)),
            "skipped": len(plan.by_action(upload_module.Action.SKIP)),
            "removed": len(plan.by_action(upload_module.Action.REMOVE)),
            "failed": len(plan.by_action(upload_module.Action.FAIL)),
            "bytes": sum(s.size for s in plan.by_action(upload_module.Action.UPLOAD)),
            "written": done,
            "dry_run": dry_run,
            "only": len(only),
        }
        items = [
            {"path": step.key, "status": step.action.value, "detail": step.reason}
            for step in plan.steps
            if step.action is not upload_module.Action.SKIP
        ]
        errors = [
            *plan.blockers,
            *(f"{s.key}: {s.reason}" for s in plan.by_action(upload_module.Action.FAIL)),
        ]
    except ZoneScopeError as exc:
        errors.append(f"ZONE SCOPE REFUSED: {exc}")
    except (
        UploadUnavailable,
        r2_module.R2Error,
        CloudflareError,
        ManifestError,
        CatalogError,
        OSError,
        ValueError,
    ) as exc:
        errors.append(str(exc))
    sys.exit(
        _emit("upload", ok=not errors, summary=summary, items=items, errors=errors, as_json=as_json)
    )


@main.command("purge")
@click.option("--site", "site", is_flag=True, help="Purge the site keys and format pages.")
@click.option("--url", "url", help="Purge one URL (takedown only, docs/11 §7.8).")
@click.option("--json", "as_json", is_flag=True, help="Print one JSON object.")
def purge_command(site: bool, url: str | None, as_json: bool) -> None:
    """Purge cached site content (docs/09 §6).

    Fixtures are never purged by `--site`: their bytes never change, so a purge could
    only discard a still-correct entry and cost an R2 read to refetch identical bytes.
    `--url` is the takedown path and names the URL explicitly.
    """
    errors: list[str] = []
    summary: dict[str, Any] = {}
    try:
        client = Client.from_env()
        client.verify_zone()
        if url:
            report = purge_module.purge_removed_url(client, url)
        elif site:
            formats = sorted({f.format for f in Catalog.load().fixtures()})
            prefixes, files = purge_module.site_targets(formats)
            report = purge_module.purge(client, prefixes, files)
        else:
            raise ValueError("choose --site or --url")
        click.echo(report.render(), err=True)
        summary = {"batches": report.batches, "prefixes": report.prefixes, "files": report.files}
        errors = report.errors
    except ZoneScopeError as exc:
        errors.append(f"ZONE SCOPE REFUSED — nothing was purged: {exc}")
    except (CloudflareError, CatalogError, ValueError) as exc:
        errors.append(str(exc))
    sys.exit(
        _emit("purge", ok=not errors, summary=summary, items=[], errors=errors, as_json=as_json)
    )


@main.command("verify-live")
@click.option(
    "--mode",
    type=click.Choice(["smoke", "daily", "full"]),
    default="smoke",
    help="How much of the catalog to check (docs/12 §4).",
)
@click.option(
    "--inject-failure",
    metavar="PATH",
    help="Report PATH as failing without it being so, to exercise the issue automation.",
)
@click.option(
    "--only",
    "only",
    multiple=True,
    metavar="PATH",
    help="Check only these manifest paths, whatever --mode says.",
)
@click.option("--json", "as_json", is_flag=True, help="Print one JSON object.")
def verify_live_command(
    mode: str, inject_failure: str | None, only: tuple[str, ...], as_json: bool
) -> None:
    """Check production against the manifest (docs/12 §4). Needs no credentials."""
    errors: list[str] = []
    report = verify_live_module.LiveReport()
    try:
        manifest = Manifest.load()
        entries = list(manifest.active)
        if only:
            # An explicit list beats the mode's sampling: the point of naming paths is to
            # check those paths, and `smoke` would otherwise silently drop most of them.
            chosen = _restrict(entries, only)
        else:
            chosen = verify_live_module.smallest_per_format(entries) if mode == "smoke" else entries
        for entry in chosen:
            response = verify_live_module.fetch(f"/{entry['path']}")
            report.findings += verify_live_module.check_fixture_headers(entry, response)
            small = entry["bytes"] < verify_live_module.DAILY_HASH_LIMIT_BYTES
            hash_it = mode == "full" or (mode == "daily" and small)
            if hash_it:
                body = verify_live_module.fetch(f"/{entry['path']}", method="GET")
                report.findings.append(verify_live_module.check_fixture_bytes(entry, body))
        if inject_failure:
            # REQ-27: the issue automation is a control, and a control nobody has seen
            # fire is one nobody can trust. This makes it fire on demand.
            report.add(
                inject_failure,
                verify_live_module.Status.HASH_MISMATCH,
                "injected by --inject-failure; not a real mismatch",
            )
        click.echo(report.render(), err=True)
        errors = [f"{f.path}: {f.status.value} {f.detail}".strip() for f in report.failures()]
    except (ManifestError, OSError, ValueError) as exc:
        errors.append(str(exc))
    sys.exit(
        _emit(
            "verify-live",
            ok=not errors,
            summary={
                "mode": "only" if only else mode,
                "checked": len(report.findings),
                "failing": len(errors),
            },
            items=[
                {"path": f.path, "status": f.status.value, "detail": f.detail}
                for f in report.findings
            ],
            errors=errors,
            as_json=as_json,
        )
    )


