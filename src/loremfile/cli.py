Item = dict[str, str]


def _restrict(entries: list[dict[str, Any]], only: tuple[str, ...]) -> list[dict[str, Any]]:
    """Narrow manifest entries to `--only`, refusing a path the manifest does not hold.

    Silently ignoring an unknown path is how a staged publish reports success over an
    empty selection: "verified 0 of the paths you named" and "verified them all" render
    the same in a summary line.
    """
    if not only:
        return entries
    wanted = set(only)
    unknown = wanted - {entry["path"] for entry in entries}
    if unknown:
        raise ValueError(f"--only names paths not in the manifest: {', '.join(sorted(unknown))}")
    return [entry for entry in entries if entry["path"] in wanted]


def _zone_client() -> Client:
    """A Cloudflare client that has confirmed which zone it is pointed at.

    The account holds unrelated production zones (docs/10 §3), and a purge is a write.
    """
    client = Client.from_env()
    client.verify_zone()
    return client


#: `infra audit` distinguishes its two failures, because they have different remedies
#: and must open and close independently (docs/11 §7.2). The one that matters is
#: `AUDIT_UNUSABLE`: an audit that could not run has learned **nothing** about drift, so
#: the caller must leave the drift issue exactly as it found it. Collapsing the two would
#: let a run that failed on a bad token close a genuine drift issue.
AUDIT_CLEAN = 0
AUDIT_DRIFT = 1
AUDIT_UNUSABLE = 2
AUDIT_OUTCOMES = {AUDIT_CLEAN: "clean", AUDIT_DRIFT: "drift", AUDIT_UNUSABLE: "unusable"}


class UploadUnavailable(RuntimeError):
    """A publish mode whose producer does not exist yet.

    Raised rather than reported as a success over an empty directory: "uploaded 0 site
    objects" and "there is no site" look identical in a log, and only one of them means
    the deploy did its job.
    """


def _emit(
    command: str,
    *,
    ok: bool,
    summary: dict[str, Any],
    items: list[Item],
    errors: list[str],
    as_json: bool,
    extra: dict[str, Any] | None = None,
) -> int:
    if as_json:
        click.echo(
            json.dumps(
                {
                    "command": command,
                    "ok": ok,
                    "summary": summary,
                    "items": items,
                    "errors": errors,
                    **(extra or {}),
                },
                indent=2,
                ensure_ascii=False,
            )
        )
    else:
        for error in errors:
            click.echo(f"error: {error}", err=True)
        parts = ", ".join(f"{key}={value}" for key, value in summary.items())
        click.echo(f"{command}: {'ok' if ok else 'FAILED'}{f' ({parts})' if parts else ''}")
    return 0 if ok else 1


