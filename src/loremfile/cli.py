@main.group()
def manifest() -> None:
    """Work with manifest.json, sha256sums.txt and formats.json."""


def _names_a_path(message: str, paths: set[str]) -> bool:
    """Does this diagnostic concern one of `paths`? Lock diffs lead with `<path>: `.

    Matched exactly, never by prefix. The set is five enumerable paths, so a prefix
    match would be broader than the evidence supports and would invite marking `opus/`
    wholesale later — which would silently exempt every future Opus fixture from the
    strongest check the project has.
    """
    head, separator, _ = message.partition(": ")
    return bool(separator) and head in paths


def _check_manifest_against_catalog() -> tuple[Manifest, list[str]]:
    """Rules that need no generated bytes: removals, totals, internal consistency."""
    loaded = Manifest.load()
    errors: list[str] = []
    try:
        catalog_obj = Catalog.load()
    except (CatalogError, ValueError) as exc:
        return loaded, [str(exc)]

    catalog_paths = {f.path for f in catalog_obj.fixtures()}
    removable = {f.path: f.removed for f in catalog_obj.fixtures() if f.removed is not None}
    errors += loaded.check_removals(catalog_paths, removable)
    errors += loaded.check_total_bytes()
    return loaded, errors


def _entries_from_build(
    catalog_obj: Catalog, committed: Manifest
) -> tuple[list[dict[str, Any]], list[str]]:
    """Build manifest entries from whatever is in build/fixtures/.

    Only fixtures that were actually generated are considered, so `manifest update`
    after a partial build adds only what that build produced. Every entry is validated
    first: an entry never reaches the manifest without its props being measured.
    """
    build_module.load_generators()
    validators.load()
    directory = build_module.fixtures_dir()
    entries: list[dict[str, Any]] = []
    errors: list[str] = []
    existing = committed.by_path

    for fixture in catalog_obj.fixtures():
        target = directory / fixture.path
        if not target.is_file() or fixture.awaiting_publication:
            continue
        data = target.read_bytes()
        mime = catalog_obj.mime_for(fixture)
        report = validators.validate(data, fixture, mime)
        if not report.ok:
            errors += [f"{fixture.path}: {failure}" for failure in report.failures]
            continue
        entry = build_entry(
            fixture,
            data,
            report.props,
            mime,
            added_in=existing.get(fixture.path, {}).get("added_in", config.CATALOG_VERSION),
        )
        entries.append(entry)

    # The lock rule is the point of the whole exercise: refuse before writing.
    diffs = committed.check_lock({e["path"]: e for e in entries})
    errors += [str(diff) for diff in diffs]
    return entries, errors


@manifest.command("check")
@click.option("--json", "as_json", is_flag=True, help="Print one JSON object.")
def manifest_check(as_json: bool) -> None:
    """Verify the committed manifest, including against whatever the build produced.

    docs/06 §7: for every fixture generated in this run, the committed `sha256`, `bytes`
    and `mime` must equal the regenerated values. That half was deferred to M3 and is
    implemented here, in M3.6 — the first milestone where an author's machine and CI
    actually disagreed, because libx264, libvpx and libopus each dispatch on the CPU
    features they find and no ffmpeg flag reaches that choice.

    When they disagree, docs/11 §5 promises the exact entries to commit rather than a
    pair of truncated hashes, so the author can take CI's answer without guessing.
    """
    loaded, errors = _check_manifest_against_catalog()
    items: list[Item] = []
    corrections: list[dict[str, Any]] = []
    regenerated: list[dict[str, Any]] = []
    if not errors:
        catalog_for_check = Catalog.load()
        try:
            regenerated, lock_errors = _entries_from_build(catalog_for_check, loaded)
        except (build_module.BuildError, CatalogError, ValueError, KeyError) as exc:
            lock_errors = [str(exc)]
        # A path marked `expected_drift` is known not to reproduce byte for byte, so a
        # mismatch on it is reported and does not fail. M3.6 measured why: two attempts
        # of the *same* commit on the *same* runner label produced different bytes for
        # opus/30s.opus and webm/720p-5s-vp9.webm, and a check that cannot pass twice in
        # a row is a check that gets disabled. Everything else stays fatal.
        drift_expected = {f.path for f in catalog_for_check.fixtures() if f.expected_drift}
        # Published on the base branch already, so its bytes are in the bucket and a
        # rebuild that drifts says nothing. New here, and they exist only in this run.
        published_before = set(build_module.merge_base_manifest().by_path)
        errors += [e for e in lock_errors if not _names_a_path(e, drift_expected)]
        committed = loaded.by_path
        for entry in regenerated:
            old = committed.get(entry["path"])
            if old is None:
                continue
            differing = [f for f in LOCKED_FIELDS if old.get(f) != entry.get(f)]
            if not differing:
                continue
            if entry["path"] in drift_expected:
                if entry["path"] not in published_before:
                    # The guard this milestone was missing. A path whose bytes cannot be
                    # rebuilt may only enter the manifest in a run that produced those
                    # exact bytes — that run's carry-forward artifact is then the only
                    # copy, and it matches. Entering on a run that drifted is how five
                    # entries came to describe bytes that existed nowhere.
                    errors.append(
                        f"{entry['path']}: new in this branch, marked expected_drift, and "
                        "the bytes this run built do not match the committed entry. Its "
                        "bytes cannot be rebuilt later, so commit the entry this run "
                        "produced (`manifest adopt`) or withhold it with "
                        "awaiting_publication (docs/03 §7.1)."
                    )
                    items.append(
                        {"path": entry["path"], "status": "unfulfillable", "detail": "no bytes"}
                    )
                    corrections.append(entry)
                    continue
                items.append(
                    {
                        "path": entry["path"],
                        "status": "expected-drift",
                        "detail": ",".join(differing),
                    }
                )
                # Still printed, though it does not fail: until the deploy publishes
                # them these entries are adoptable, and the manifest has to describe the
                # same bytes as the carry-forward artifact from this very run.
                corrections.append(entry)
                continue
            corrections.append(entry)
            items.append(
                {"path": entry["path"], "status": "differs", "detail": ",".join(differing)}
            )
        errors += [
            w
            for w in loaded.props_warnings({e["path"]: e for e in regenerated})
            if not _names_a_path(w, drift_expected)
        ]
        expected_seen = [i for i in items if i["status"] == "expected-drift"]
        if expected_seen and not as_json:
            click.echo(
                "\nExpected drift, not a failure (docs/06 §4 — these do not reproduce "
                "byte for byte between runs):",
                err=True,
            )
            for item in expected_seen:
                click.echo(f"  {item['path']}: {item['detail']}", err=True)

    active = loaded.active
    summary = {
        "entries": len(loaded.entries),
        "active": len(active),
        "tombstones": len(loaded.entries) - len(active),
        "total_bytes": sum(e["bytes"] for e in active),
        "regenerated": len(regenerated),
    }
    if corrections and not as_json:
        click.echo(
            "\nThe bytes this machine produced differ from the committed manifest. "
            "Encoder libraries dispatch on CPU features, so an author's machine and CI "
            "can disagree; CI is the authority (docs/06 §4). Commit these entries:\n",
            err=True,
        )
        click.echo(json.dumps(corrections, indent=2, ensure_ascii=False, sort_keys=True))
    sys.exit(
        _emit(
            "manifest check",
            ok=not errors,
            summary=summary,
            items=items,
            errors=errors,
            as_json=as_json,
        )
    )


@manifest.command("adopt")
@click.option(
    "--from",
    "source",
    required=True,
    type=click.Path(exists=True, dir_okay=False, path_type=Path),
    help="JSON array of entries, as `manifest check` prints them.",
)
@click.option("--json", "as_json", is_flag=True, help="Print one JSON object.")
def manifest_adopt(source: Path, as_json: bool) -> None:
    """Take CI's entries for fixtures this machine cannot reproduce (docs/06 §4).

    libx264, libvpx and libopus dispatch on the CPU features they find, so an author's
    machine and CI can produce different bytes for the same fixture and no ffmpeg flag
    reaches that choice. CI is the authority, because CI is what builds the bytes the
    deploy uploads — so its entries have to be committable without hand-editing the
    manifest, which AGENTS.md forbids for good reason.

    The refusal that matters is the last one: a fixture already published on the base
    branch may never change its bytes, whatever any machine now produces. Adopting is
    only ever allowed for paths this branch is adding.
    """
    errors: list[str] = []
    items: list[Item] = []
    adopted: list[dict[str, Any]] = []
    try:
        incoming = json.loads(source.read_text(encoding="utf-8"))
        if not isinstance(incoming, list):
            raise ValueError("expected a JSON array of manifest entries")
        loaded = Manifest.load()
        catalog_obj = Catalog.load()
        mime_defaults = {fmt.format: fmt.mime for fmt in catalog_obj.formats}
        known = catalog_obj.by_path
        published = build_module.merge_base_manifest().by_path

        for entry in incoming:
            path = entry.get("path")
            if path not in known:
                errors.append(f"{path}: not in the catalog")
                continue
            missing = [f for f in (*LOCKED_FIELDS, "path", "props") if f not in entry]
            if missing:
                errors.append(f"{path}: entry is missing {missing}")
                continue
            was = published.get(path)
            if was is not None:
                frozen = [f for f in LOCKED_FIELDS if was.get(f) != entry.get(f)]
                if frozen:
                    errors.append(
                        f"{path}: already published on the base branch and {frozen} would "
                        "change. Published bytes are frozen forever (docs/01 REQ-2): "
                        "publish a new path with supersededBy instead."
                    )
                    continue
            adopted.append(entry)
            items.append({"path": path, "status": "adopted", "detail": entry["sha256"][:12]})

        if not errors:
            by_path = loaded.by_path
            changed = any(by_path.get(e["path"]) != e for e in adopted)
            for entry in adopted:
                by_path[entry["path"]] = entry
            loaded.entries = sorted(by_path.values(), key=lambda e: e["path"])
            loaded.touch(changed=changed)
            loaded.save()
            config.sha256sums_path().write_text(
                render_sha256sums(loaded), encoding="utf-8", newline="\n"
            )
            config.formats_json_path().write_text(
                render_formats_json(loaded, mime_defaults), encoding="utf-8", newline="\n"
            )
    except (ManifestError, CatalogError, OSError, ValueError, KeyError) as exc:
        errors.append(str(exc))
    sys.exit(
        _emit(
            "manifest adopt",
            ok=not errors,
            summary={"adopted": len(adopted) if not errors else 0},
            items=items,
            errors=errors,
            as_json=as_json,
        )
    )


@manifest.command("update")
@click.option("--json", "as_json", is_flag=True, help="Print one JSON object.")
def manifest_update(as_json: bool) -> None:
    """Rewrite manifest.json, sha256sums.txt and formats.json.

    Never hand-edit those files: run this inside the toolchain container and commit
    exactly what it writes (AGENTS.md).
    """
    loaded, errors = _check_manifest_against_catalog()
    if errors:
        sys.exit(
            _emit("manifest update", ok=False, summary={}, items=[], errors=errors, as_json=as_json)
        )
    try:
        catalog_obj = Catalog.load()
        mime_defaults = {fmt.format: fmt.mime for fmt in catalog_obj.formats}
        added, lock_errors = _entries_from_build(catalog_obj, loaded)
        if lock_errors:
            sys.exit(
                _emit(
                    "manifest update",
                    ok=False,
                    summary={},
                    items=[],
                    errors=lock_errors,
                    as_json=as_json,
                )
            )
        by_path = loaded.by_path
        # docs/03 §7.1, amended in M3.6: immutability attaches on publication to R2, not
        # on entry into the manifest. A fixture marked `awaiting_publication` therefore
        # leaves the manifest outright rather than becoming a tombstone, which would
        # assert a publication that never happened. The guard is that it may never have
        # been published: anything present on the base branch stays, and says so.
        published = build_module.merge_base_manifest().by_path
        withdrawn: list[str] = []
        for fixture in catalog_obj.fixtures():
            if not fixture.awaiting_publication or fixture.path not in by_path:
                continue
            if fixture.path in published:
                sys.exit(
                    _emit(
                        "manifest update",
                        ok=False,
                        summary={},
                        items=[],
                        errors=[
                            f"{fixture.path}: awaiting_publication, but it is already in "
                            "the base branch manifest. Withdrawing a published path is "
                            "forbidden (docs/03 §7.1); use a tombstone or supersede it."
                        ],
                        as_json=as_json,
                    )
                )
            del by_path[fixture.path]
            withdrawn.append(fixture.path)

        # docs/06 §7 step 5: generated_at moves only when something actually changed,
        # so an unchanged rebuild produces no diff at all. Comparing the assembled
        # entries — not merely "did we build anything" — is what makes that true.
        changed = bool(withdrawn) or any(by_path.get(entry["path"]) != entry for entry in added)
        for entry in added:
            by_path[entry["path"]] = entry
        loaded.entries = sorted(by_path.values(), key=lambda e: e["path"])
        changed = changed or loaded.catalog_version != config.CATALOG_VERSION
        loaded.catalog_version = config.CATALOG_VERSION
        loaded.touch(changed=changed)
        loaded.save()
        config.sha256sums_path().write_text(
            render_sha256sums(loaded), encoding="utf-8", newline="\n"
        )
        config.formats_json_path().write_text(
            render_formats_json(loaded, mime_defaults), encoding="utf-8", newline="\n"
        )
    except (ManifestError, CatalogError, OSError) as exc:
        sys.exit(
            _emit(
                "manifest update",
                ok=False,
                summary={},
                items=[],
                errors=[str(exc)],
                as_json=as_json,
            )
        )
    sys.exit(
        _emit(
            "manifest update",
            ok=True,
            summary={
                "entries": len(loaded.entries),
                "active": len(loaded.active),
                "withdrawn": len(withdrawn),
            },
            items=[],
            errors=[],
            as_json=as_json,
        )
    )


